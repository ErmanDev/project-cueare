/*
SSC Attendance — PostgreSQL schema for database [aclc], schema ssc

Single-school install (no tenants table). Role lives on "Users".

  Database: aclc
  Schema:   ssc

Quoted identifiers: PascalCase tables, camelCase columns.
REST JSON / Flutter field names stay snake_case.

External sign-in:
  "AuthProviders" lookup (google, microsoft, apple)
  "ExternalLogins" links a "Users" row to one IdP subject

App-needed extra columns:
  "Users"."passwordHash", "Users".role, "Users"."updatedAtUtc"
  "Students"."photoUrl", "Students"."updatedAtUtc"
  "Events"."eventDate", "Events"."updatedAtUtc"
  "EventSessions"."sortOrder"
  "AttendanceLogs"."deviceNote", "AttendanceLogs"."isCancelled"

Connect to database aclc before running. The Node server applies the same
definitions via server/src/db/schema.ts (preferred).
*/

CREATE SCHEMA IF NOT EXISTS ssc;

SET search_path TO ssc;

CREATE OR REPLACE FUNCTION new_row_version()
     RETURNS bytea
     LANGUAGE sql
     AS $$
       SELECT decode(substr(md5(random()::text || clock_timestamp()::text), 1, 16), 'hex')
     $$;

CREATE OR REPLACE FUNCTION bump_row_version()
     RETURNS trigger
     LANGUAGE plpgsql
     AS $$
     BEGIN
       NEW."rowVersion" := new_row_version();
       RETURN NEW;
     END;
     $$;


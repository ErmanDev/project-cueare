CREATE OR REPLACE VIEW "AttendanceSessionStatus" AS
     SELECT
       r."attendanceRecordId",
       ep."eventSessionId",
       ep."studentId",
       ep."studentEnrollmentId",
       r."checkedInAtUtc",
       r."checkedOutAtUtc",
       r."isExcused",
       r."excuseReason",
       CASE
         WHEN r."isExcused" THEN 'EXCUSED'
         WHEN r."checkedInAtUtc" IS NULL THEN 'ABSENT'
         WHEN r."checkedInAtUtc" > es."lateAfterUtc" THEN 'LATE'
         ELSE 'PRESENT'
       END AS "attendanceStatusCode",
       CASE
         WHEN r."checkedInAtUtc" IS NOT NULL AND r."checkedOutAtUtc" IS NOT NULL
           THEN floor(extract(epoch FROM (r."checkedOutAtUtc" - r."checkedInAtUtc")) / 60)::int
         ELSE NULL
       END AS "minutesPresent"
     FROM "AttendanceRecords" r
     JOIN "EventParticipants" ep ON ep."eventParticipantId" = r."eventParticipantId"
     JOIN "EventSessions" es ON es."eventSessionId" = ep."eventSessionId";


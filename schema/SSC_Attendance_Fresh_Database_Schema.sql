CREATE TABLE IF NOT EXISTS "EventSessions" (
      "eventSessionId" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "eventId" bigint NOT NULL,
      "academicTermId" bigint NOT NULL,
      "sessionCode" varchar(30) NOT NULL,
      "sessionName" varchar(100) NOT NULL,
      "startsAtUtc" timestamptz(3) NOT NULL,
      "endsAtUtc" timestamptz(3) NOT NULL,
      "checkInOpensAtUtc" timestamptz(3) NOT NULL,
      "checkInClosesAtUtc" timestamptz(3) NOT NULL,
      "lateAfterUtc" timestamptz(3) NOT NULL,
      "checkOutOpensAtUtc" timestamptz(3) NOT NULL,
      "checkOutClosesAtUtc" timestamptz(3) NOT NULL,
      "requiresCheckOut" boolean NOT NULL DEFAULT true,
      "minimumMinutes" integer NOT NULL DEFAULT 0,
      "isClosed" boolean NOT NULL DEFAULT false,
      "sortOrder" integer NOT NULL DEFAULT 0,
      "createdAtUtc" timestamptz(3) NOT NULL DEFAULT clock_timestamp(),
      "rowVersion" bytea NOT NULL DEFAULT new_row_version(),
      CONSTRAINT uq_event_sessions_context UNIQUE ("eventSessionId", "academicTermId"),
      CONSTRAINT uq_event_sessions_code UNIQUE ("eventId", "sessionCode"),
      CONSTRAINT fk_event_sessions_event FOREIGN KEY ("eventId", "academicTermId")
        REFERENCES "Events" ("eventId", "academicTermId") ON DELETE CASCADE,
      CONSTRAINT ck_event_sessions_dates CHECK (
        "startsAtUtc" < "endsAtUtc"
        AND "checkInOpensAtUtc" <= "startsAtUtc"
        AND "checkInClosesAtUtc" >= "startsAtUtc"
        AND "checkInClosesAtUtc" <= "endsAtUtc"
        AND "lateAfterUtc" >= "startsAtUtc"
        AND "lateAfterUtc" <= "checkInClosesAtUtc"
        AND "checkOutOpensAtUtc" >= "startsAtUtc"
        AND "checkOutOpensAtUtc" <= "checkOutClosesAtUtc"
        AND "checkOutClosesAtUtc" >= "endsAtUtc"
      ),
      CONSTRAINT ck_event_sessions_minutes CHECK (
        "minimumMinutes" >= 0 AND ("requiresCheckOut" = true OR "minimumMinutes" = 0)
      )
    );


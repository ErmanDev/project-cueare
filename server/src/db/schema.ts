type Queryable = {
  query: (text: string, values?: unknown[]) => Promise<{ rows: Record<string, unknown>[]; rowCount: number | null }>;
};

async function relationExists(db: Queryable, name: string): Promise<boolean> {
  const res = await db.query('SELECT to_regclass($1) AS rel', [name]);
  return res.rows[0]?.rel != null;
}

async function columnExists(db: Queryable, table: string, column: string): Promise<boolean> {
  const res = await db.query(
    `SELECT 1 FROM information_schema.columns
     WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2`,
    [table, column],
  );
  return (res.rowCount ?? 0) > 0;
}

async function addColumnIfMissing(
  db: Queryable,
  table: string,
  column: string,
  spec: string,
): Promise<void> {
  if (!(await relationExists(db, q(table)))) return;
  if (await columnExists(db, table, column)) return;
  await db.query(`ALTER TABLE ${q(table)} ADD COLUMN ${spec}`);
}


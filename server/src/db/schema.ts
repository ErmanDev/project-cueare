export async function addMissingAppColumns(db: Queryable): Promise<void> {
  await addColumnIfMissing(db, 'Users', 'username', 'username varchar(100)');
  await addColumnIfMissing(db, 'Users', 'passwordHash', `${q('passwordHash')} text`);
  await addColumnIfMissing(db, 'Users', 'role', 'role varchar(20)');
  await addColumnIfMissing(
    db,
    'Users',
    'updatedAtUtc',
    `${q('updatedAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()`,
  );
  if (await columnExists(db, 'Users', 'externalSubject')) {
    await db.query(
      `ALTER TABLE ${q('Users')} ALTER COLUMN ${q('externalSubject')} DROP NOT NULL`,
    );
  }

  await addColumnIfMissing(db, 'Students', 'userId', `${q('userId')} integer NULL`);
  await addColumnIfMissing(db, 'Students', 'photoUrl', `${q('photoUrl')} text NULL`);
  await addColumnIfMissing(
    db,
    'Students',
    'updatedAtUtc',
    `${q('updatedAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()`,
  );

  const { rows: eventDateCheck } = await db.query(
    `SELECT column_name FROM information_schema.columns WHERE table_name = 'Events' AND column_name = 'eventDate'`
  );
  if (eventDateCheck.length > 0) {
    await db.query(`ALTER TABLE ${q('Events')} RENAME COLUMN ${q('eventDate')} TO ${q('eventStartDate')}`);
  }
  await addColumnIfMissing(db, 'Events', 'eventStartDate', `${q('eventStartDate')} date`);
  await addColumnIfMissing(db, 'Events', 'eventEndDate', `${q('eventEndDate')} date`);
  if (await relationExists(db, q('Events'))) {
    await db.query(`UPDATE ${q('Events')} SET ${q('eventEndDate')} = ${q('eventStartDate')} WHERE ${q('eventEndDate')} IS NULL`);
    await db.query(`ALTER TABLE ${q('Events')} ALTER COLUMN ${q('eventEndDate')} SET NOT NULL`);
  }
  await addColumnIfMissing(
    db,
    'Events',
    'updatedAtUtc',
    `${q('updatedAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()`,
  );
  await addColumnIfMissing(db, 'Events', 'description', 'description varchar(2000) NULL');
  await addColumnIfMissing(db, 'Events', 'venue', 'venue varchar(300) NULL');

  await addColumnIfMissing(
    db,
    'EventSessions',
    'sortOrder',
    `${q('sortOrder')} integer NOT NULL DEFAULT 0`,
  );
  await addColumnIfMissing(
    db,
    'EventSessions',
    'academicTermId',
    `${q('academicTermId')} bigint`,
  );
  await addColumnIfMissing(
    db,
    'EventSessions',
    'sessionTypeCode',
    `${q('sessionTypeCode')} varchar(20) NOT NULL DEFAULT 'GENERAL'`,
  );

  await addColumnIfMissing(
    db,
    'EventParticipants',
    'academicTermId',
    `${q('academicTermId')} bigint`,
  );
  await addColumnIfMissing(
    db,
    'EventParticipants',
    'studentEnrollmentId',
    `${q('studentEnrollmentId')} bigint`,
  );
  await addColumnIfMissing(
    db,
    'EventParticipants',
    'eventRegistrationId',
    `${q('eventRegistrationId')} bigint NULL`,
  );

  await addColumnIfMissing(
    db,
    'FinePolicyTemplates',
    'updatedAtUtc',
    `${q('updatedAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()`,
  );

  await addColumnIfMissing(
    db,
    'AttendanceLogs',
    'isCancelled',
    `${q('isCancelled')} boolean NOT NULL DEFAULT false`,
  );
  await addColumnIfMissing(
    db,
    'AttendanceLogs',
    'deviceNote',
    `${q('deviceNote')} varchar(200) NULL`,
  );
  await addColumnIfMissing(
    db,
    'AttendanceLogs',
    'recordedAtUtc',
    `${q('recordedAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()`,
  );
  await addColumnIfMissing(
    db,
    'AttendanceLogs',
    'attendanceCorrectionId',
    `${q('attendanceCorrectionId')} bigint NULL`,
  );
  if ((await relationExists(db, q('Events'))) && !(await relationExists(db, q('EventAudienceRules')))) {
    await db.query(
      `CREATE TABLE ${q('EventAudienceRules')} (
        ${q('eventAudienceRuleId')} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ${q('eventId')} bigint NOT NULL,
        ${q('academicTermId')} bigint NOT NULL,
        ${q('audienceScopeCode')} varchar(20) NOT NULL,
        ${q('academicProgramId')} bigint NULL,
        ${q('sectionId')} bigint NULL,
        ${q('yearLevel')} smallint NULL,
        ${q('studentId')} bigint NULL,
        ${q('isRequired')} boolean NOT NULL DEFAULT true,
        ${q('createdByUserId')} integer NOT NULL,
        ${q('createdAtUtc')} timestamptz(3) NOT NULL DEFAULT clock_timestamp()
      )`,
    );
    await db.query(`CREATE INDEX ix_event_audience_rules_event ON ${q('EventAudienceRules')} (${q('eventId')})`);
  }
  await addColumnIfMissing(
    db,
    'EventRegistrations',
    'sourceAudienceRuleId',
    `${q('sourceAudienceRuleId')} bigint NULL`,
  );

  await addColumnIfMissing(
    db,
    'EventParticipantQrCredentials',
    'token',
    'token uuid NULL',
  );
  if (await columnExists(db, 'EventParticipantQrCredentials', 'token')) {
    if (await relationExists(db, q('EventParticipantTokens'))) {
      await db.query(
        `UPDATE ${q('EventParticipantQrCredentials')} c
         SET token = t.token
         FROM ${q('EventRegistrations')} er, ${q('EventParticipantTokens')} t
         WHERE c.${q('eventRegistrationId')} = er.${q('eventRegistrationId')}
           AND t.${q('eventId')} = er.${q('eventId')}
           AND t.${q('studentId')} = er.${q('studentId')}
           AND c.token IS NULL`,
      );
    }
    await db.query(
      `UPDATE ${q('EventParticipantQrCredentials')}
       SET token = gen_random_uuid()
       WHERE token IS NULL`,
    );
    await db.query(
      `UPDATE ${q('EventParticipantQrCredentials')}
       SET ${q('tokenHash')} = decode(md5(token::text), 'hex')
       WHERE ${q('tokenHash')} IS NULL
          OR ${q('tokenHash')} <> decode(md5(token::text), 'hex')`,
    );
    await db.query(`ALTER TABLE ${q('EventParticipantQrCredentials')} ALTER COLUMN token SET DEFAULT gen_random_uuid()`);
    await db.query(`ALTER TABLE ${q('EventParticipantQrCredentials')} ALTER COLUMN token SET NOT NULL`);
    await ignoreDuplicate(
      db,
      `CREATE UNIQUE INDEX IF NOT EXISTS ux_event_participant_qr_credentials_token
       ON ${q('EventParticipantQrCredentials')} (token)`,
    );
  }

  if (!(await relationExists(db, q('EventSessionQrTokens')))) {
    await db.query(`
      CREATE TABLE IF NOT EXISTS ${q('EventSessionQrTokens')} (
        ${q('eventSessionQrTokenId')} bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        ${q('eventSessionId')} bigint NOT NULL REFERENCES ${q('EventSessions')}(${q('eventSessionId')}) ON DELETE CASCADE,
        ${q('actionCode')} varchar(4) NOT NULL,
        ${q('tokenHash')} bytea NOT NULL,
        ${q('validFromUtc')} timestamptz NOT NULL DEFAULT clock_timestamp(),
        ${q('expiresAtUtc')} timestamptz NOT NULL,
        ${q('issuedByUserId')} integer NOT NULL REFERENCES ${q('Users')}(${q('userId')}),
        ${q('issuedAtUtc')} timestamptz NOT NULL DEFAULT clock_timestamp(),
        ${q('revokedAtUtc')} timestamptz NULL,
        ${q('revokedByUserId')} integer NULL REFERENCES ${q('Users')}(${q('userId')}),
        ${q('revocationReason')} varchar(500) NULL,
        CONSTRAINT uq_event_session_qr_tokens_hash UNIQUE (${q('tokenHash')}),
        CONSTRAINT ck_event_session_qr_tokens_action CHECK (${q('actionCode')} IN ('IN', 'OUT', 'AUTO')),
        CONSTRAINT ck_event_session_qr_tokens_validity CHECK (${q('validFromUtc')} < ${q('expiresAtUtc')}),
        CONSTRAINT ck_event_session_qr_tokens_revoke CHECK (
          (${q('revokedAtUtc')} IS NULL AND ${q('revokedByUserId')} IS NULL AND ${q('revocationReason')} IS NULL)
          OR (${q('revokedAtUtc')} IS NOT NULL AND ${q('revokedByUserId')} IS NOT NULL AND ${q('revocationReason')} IS NOT NULL AND char_length(btrim(${q('revocationReason')})) > 0)
        )
      )
    `);
    await ignoreDuplicate(db, `CREATE INDEX IF NOT EXISTS ix_event_session_qr_tokens_lookup ON ${q('EventSessionQrTokens')} (${q('eventSessionId')}, ${q('actionCode')}, ${q('expiresAtUtc')}) WHERE ${q('revokedAtUtc')} IS NULL`);
    await ignoreDuplicate(db, `CREATE INDEX IF NOT EXISTS ix_event_session_qr_tokens_hash ON ${q('EventSessionQrTokens')} (${q('tokenHash')})`);
  }

  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'eventSessionQrTokenId', `${q('eventSessionQrTokenId')} bigint NULL REFERENCES ${q('EventSessionQrTokens')}(${q('eventSessionQrTokenId')})`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'resolvedStudentId', `${q('resolvedStudentId')} bigint NULL REFERENCES ${q('Students')}(${q('studentId')})`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'scanMethodCode', `${q('scanMethodCode')} varchar(30) NOT NULL DEFAULT 'STAFF_SCANNED_STUDENT_QR'`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'clientRequestId', `${q('clientRequestId')} uuid NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'clientFingerprintHash', `${q('clientFingerprintHash')} bytea NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'ipAddress', `${q('ipAddress')} inet NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'latitude', `${q('latitude')} numeric(9,6) NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'longitude', `${q('longitude')} numeric(9,6) NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'locationAccuracyMeters', `${q('locationAccuracyMeters')} numeric(10,2) NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'attendanceStatusCode', `${q('attendanceStatusCode')} varchar(30) NULL`);
  await addColumnIfMissing(db, 'AttendanceScanAttempts', 'attendanceEffectiveAtUtc', `${q('attendanceEffectiveAtUtc')} timestamptz NULL`);

  if (await relationExists(db, q('AttendanceScanAttempts'))) {
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} ALTER COLUMN ${q('eventSessionId')} DROP NOT NULL`);
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} ALTER COLUMN ${q('actionCode')} DROP NOT NULL`);
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} DROP CONSTRAINT IF EXISTS ck_attendance_scan_attempts_method`);
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} ADD CONSTRAINT ck_attendance_scan_attempts_method CHECK (${q('scanMethodCode')} IN ('STUDENT_SCANNED_EVENT_QR', 'STAFF_SCANNED_STUDENT_QR', 'MANUAL_STUDENT_NUMBER', 'ADMIN_CORRECTION'))`);
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} DROP CONSTRAINT IF EXISTS ck_attendance_scan_attempts_result`);
    await ignoreDuplicate(db, `ALTER TABLE ${q('AttendanceScanAttempts')} ADD CONSTRAINT ck_attendance_scan_attempts_result CHECK (${q('scanResultCode')} IN ('ACCEPTED', 'NO_CHANGE', 'REJECTED'))`);
    await ignoreDuplicate(db, `CREATE UNIQUE INDEX IF NOT EXISTS ux_attendance_scan_attempts_client_request ON ${q('AttendanceScanAttempts')} (${q('clientRequestId')}) WHERE ${q('clientRequestId')} IS NOT NULL`);
    await ignoreDuplicate(db, `CREATE INDEX IF NOT EXISTS ix_attendance_scan_attempts_user_time ON ${q('AttendanceScanAttempts')} (${q('processedByUserId')}, ${q('scannedAtUtc')})`);
    await ignoreDuplicate(db, `CREATE INDEX IF NOT EXISTS ix_attendance_scan_attempts_resolved_student_time ON ${q('AttendanceScanAttempts')} (${q('resolvedStudentId')}, ${q('scannedAtUtc')}) WHERE ${q('resolvedStudentId')} IS NOT NULL`);
  }

  if (!(await relationExists(db, q('StudentUserLinks')))) {
    await db.query(`
      CREATE TABLE IF NOT EXISTS ${q('StudentUserLinks')} (
        ${q('userId')} integer NOT NULL,
        ${q('studentId')} bigint NOT NULL,
        ${q('linkedByUserId')} integer NULL,
        ${q('linkedAtUtc')} timestamptz NOT NULL DEFAULT clock_timestamp(),
        CONSTRAINT pk_student_user_links PRIMARY KEY (${q('userId')}),
        CONSTRAINT uq_student_user_links_student UNIQUE (${q('studentId')}),
        CONSTRAINT fk_student_user_links_user FOREIGN KEY (${q('userId')}) REFERENCES ${q('Users')}(${q('userId')}) ON DELETE RESTRICT,
        CONSTRAINT fk_student_user_links_student FOREIGN KEY (${q('studentId')}) REFERENCES ${q('Students')}(${q('studentId')}) ON DELETE RESTRICT,
        CONSTRAINT fk_student_user_links_linked_by FOREIGN KEY (${q('linkedByUserId')}) REFERENCES ${q('Users')}(${q('userId')}) ON DELETE RESTRICT,
        CONSTRAINT ck_student_user_links_different_linker CHECK (${q('linkedByUserId')} IS NULL OR ${q('linkedByUserId')} <> ${q('userId')})
      )
    `);
    await ignoreDuplicate(db, `CREATE INDEX IF NOT EXISTS ix_student_user_links_student ON ${q('StudentUserLinks')} (${q('studentId')})`);
  }

  // Self-scan functions
  await ignoreDuplicate(db, `
    CREATE OR REPLACE FUNCTION fn_event_session_qr_issue(
        p_event_session_id BIGINT, p_action_code VARCHAR(4), p_token_hash BYTEA,
        p_valid_for_seconds INT, p_overlap_seconds INT, p_actor_user_id INT
    ) RETURNS TABLE ("eventSessionQrTokenId" BIGINT, "eventSessionId" BIGINT, "actionCode" VARCHAR(4), "validFromUtc" TIMESTAMPTZ, "expiresAtUtc" TIMESTAMPTZ)
    LANGUAGE plpgsql AS $function$
    DECLARE v_now TIMESTAMPTZ := clock_timestamp(); v_token_id BIGINT; v_event_status VARCHAR(20); v_session_closed BOOLEAN;
    BEGIN
        IF p_action_code NOT IN ('IN', 'OUT', 'AUTO') THEN RAISE EXCEPTION 'Action code must be IN, OUT, or AUTO.' USING ERRCODE = '22023'; END IF;
        IF p_valid_for_seconds NOT BETWEEN 15 AND 3600 THEN RAISE EXCEPTION 'QR validity must be between 15 and 3600 seconds.' USING ERRCODE = '22023'; END IF;
        IF p_overlap_seconds NOT BETWEEN 0 AND 30 THEN RAISE EXCEPTION 'QR overlap must be between 0 and 30 seconds.' USING ERRCODE = '22023'; END IF;
        IF NOT EXISTS (SELECT 1 FROM "Users" u WHERE u."userId" = p_actor_user_id AND u."isActive" = TRUE AND u."canManageAttendance" = TRUE) THEN RAISE EXCEPTION 'Active attendance manager authorization required.' USING ERRCODE = '42501'; END IF;
        SELECT e."eventStatusCode", s."isClosed" INTO v_event_status, v_session_closed FROM "EventSessions" s JOIN "Events" e ON e."eventId" = s."eventId" WHERE s."eventSessionId" = p_event_session_id FOR UPDATE OF s;
        IF NOT FOUND THEN RAISE EXCEPTION 'Event session not found.' USING ERRCODE = 'P0002'; END IF;
        IF v_event_status <> 'PUBLISHED' OR v_session_closed THEN RAISE EXCEPTION 'QR issuance requires a published event and open session.' USING ERRCODE = '55000'; END IF;
        UPDATE "EventSessionQrTokens" q SET "expiresAtUtc" = LEAST(q."expiresAtUtc", v_now + make_interval(secs => p_overlap_seconds)) WHERE q."eventSessionId" = p_event_session_id AND q."actionCode" = p_action_code AND q."revokedAtUtc" IS NULL AND q."expiresAtUtc" > v_now + make_interval(secs => p_overlap_seconds);
        INSERT INTO "EventSessionQrTokens" ("eventSessionId", "actionCode", "tokenHash", "validFromUtc", "expiresAtUtc", "issuedByUserId", "issuedAtUtc") VALUES (p_event_session_id, p_action_code, p_token_hash, v_now, v_now + make_interval(secs => p_valid_for_seconds), p_actor_user_id, v_now) RETURNING "EventSessionQrTokens"."eventSessionQrTokenId" INTO v_token_id;
        RETURN QUERY SELECT v_token_id, p_event_session_id, p_action_code, v_now, v_now + make_interval(secs => p_valid_for_seconds);
    END $function$;
  `);

  await ignoreDuplicate(db, `
    CREATE OR REPLACE PROCEDURE sp_event_session_qr_revoke(p_event_session_qr_token_id BIGINT, p_reason VARCHAR(500), p_actor_user_id INT)
    LANGUAGE plpgsql AS $procedure$
    BEGIN
        IF p_reason IS NULL OR length(trim(p_reason)) = 0 THEN RAISE EXCEPTION 'Revocation reason is required.' USING ERRCODE = '22023'; END IF;
        IF NOT EXISTS (SELECT 1 FROM "Users" u WHERE u."userId" = p_actor_user_id AND u."isActive" = TRUE AND u."canManageAttendance" = TRUE) THEN RAISE EXCEPTION 'Active attendance manager authorization required.' USING ERRCODE = '42501'; END IF;
        UPDATE "EventSessionQrTokens" SET "revokedAtUtc" = clock_timestamp(), "revokedByUserId" = p_actor_user_id, "revocationReason" = trim(p_reason) WHERE "eventSessionQrTokenId" = p_event_session_qr_token_id AND "revokedAtUtc" IS NULL;
        IF NOT FOUND THEN RAISE EXCEPTION 'Active event-session QR token not found.' USING ERRCODE = 'P0002'; END IF;
    END $procedure$;
  `);

  await ignoreDuplicate(db, `
    CREATE OR REPLACE FUNCTION fn_attendance_self_scan_event_qr(
        p_token_hash BYTEA, p_authenticated_user_id INT, p_client_request_id UUID,
        p_client_fingerprint_hash BYTEA DEFAULT NULL, p_ip_address INET DEFAULT NULL
    ) RETURNS TABLE (
        "scanResultCode" VARCHAR(20), "failureReasonCode" VARCHAR(40), "eventId" BIGINT, "eventName" VARCHAR(200),
        "eventSessionId" BIGINT, "sessionName" VARCHAR(100), "studentId" BIGINT, "studentNumber" VARCHAR(50),
        "studentFullName" VARCHAR(320), "actionRecorded" VARCHAR(3), "attendanceStatus" VARCHAR(30), "recordedAtUtc" TIMESTAMPTZ
    ) LANGUAGE plpgsql AS $function$
    DECLARE
        v_now TIMESTAMPTZ := clock_timestamp(); v_existing RECORD; v_qr_id BIGINT; v_qr_action VARCHAR(4);
        v_valid_from TIMESTAMPTZ; v_expires_at TIMESTAMPTZ; v_revoked_at TIMESTAMPTZ; v_event_id BIGINT;
        v_event_name VARCHAR(200); v_event_status VARCHAR(20); v_session_id BIGINT; v_session_name VARCHAR(100);
        v_session_closed BOOLEAN; v_in_open TIMESTAMPTZ; v_in_close TIMESTAMPTZ; v_late_after TIMESTAMPTZ;
        v_out_open TIMESTAMPTZ; v_out_close TIMESTAMPTZ; v_requires_out BOOLEAN; v_minimum_minutes SMALLINT;
        v_student_id BIGINT; v_student_number VARCHAR(50); v_student_name VARCHAR(320); v_participant_id BIGINT;
        v_attendance_record_id BIGINT; v_checked_in TIMESTAMPTZ; v_checked_out TIMESTAMPTZ; v_is_excused BOOLEAN;
        v_excuse_reason VARCHAR(500); v_action VARCHAR(3); v_result VARCHAR(20) := 'REJECTED'; v_reason VARCHAR(40);
        v_attendance_status VARCHAR(30); v_effective_at TIMESTAMPTZ;
    BEGIN
        IF p_client_request_id IS NULL THEN RAISE EXCEPTION 'clientRequestId is required.' USING ERRCODE = '22004'; END IF;
        PERFORM pg_advisory_xact_lock(hashtextextended(p_client_request_id::text, 847291));
        SELECT a.* INTO v_existing FROM "AttendanceScanAttempts" a WHERE a."clientRequestId" = p_client_request_id;
        IF FOUND THEN
            RETURN QUERY SELECT v_existing."scanResultCode"::VARCHAR(20), v_existing."failureReasonCode"::VARCHAR(40),
                e."eventId", e."eventName", s."eventSessionId", s."sessionName", st."studentId", st."studentNumber",
                concat_ws(' ', st."firstName", st."middleName", st."lastName", st.suffix)::VARCHAR(320),
                v_existing."actionCode"::VARCHAR(3), v_existing."attendanceStatusCode"::VARCHAR(30),
                COALESCE(v_existing."attendanceEffectiveAtUtc", v_existing."scannedAtUtc")
            FROM (SELECT 1) seed
            LEFT JOIN "EventSessions" s ON s."eventSessionId" = v_existing."eventSessionId"
            LEFT JOIN "Events" e ON e."eventId" = s."eventId"
            LEFT JOIN "Students" st ON st."studentId" = v_existing."resolvedStudentId";
            RETURN;
        END IF;

        SELECT q."eventSessionQrTokenId", q."actionCode", q."validFromUtc", q."expiresAtUtc", q."revokedAtUtc",
            s."eventSessionId", s."sessionName", s."isClosed", s."checkInOpensAtUtc", s."checkInClosesAtUtc", s."lateAfterUtc",
            s."checkOutOpensAtUtc", s."checkOutClosesAtUtc", s."requiresCheckOut", s."minimumMinutes",
            e."eventId", e."eventName", e."eventStatusCode"
        INTO v_qr_id, v_qr_action, v_valid_from, v_expires_at, v_revoked_at, v_session_id, v_session_name, v_session_closed,
            v_in_open, v_in_close, v_late_after, v_out_open, v_out_close, v_requires_out, v_minimum_minutes,
            v_event_id, v_event_name, v_event_status
        FROM "EventSessionQrTokens" q JOIN "EventSessions" s ON s."eventSessionId" = q."eventSessionId" JOIN "Events" e ON e."eventId" = s."eventId"
        WHERE q."tokenHash" = p_token_hash;

        IF NOT FOUND THEN v_reason := 'INVALID_QR_TOKEN';
        ELSIF v_revoked_at IS NOT NULL THEN v_reason := 'REVOKED_QR_TOKEN';
        ELSIF v_now < v_valid_from THEN v_reason := 'QR_NOT_YET_VALID';
        ELSIF v_now >= v_expires_at THEN v_reason := 'EXPIRED_QR_TOKEN';
        ELSIF v_event_status = 'CANCELLED' THEN v_reason := 'EVENT_CANCELLED';
        ELSIF v_event_status <> 'PUBLISHED' THEN v_reason := 'EVENT_NOT_PUBLISHED';
        ELSIF v_session_closed THEN v_reason := 'SESSION_CLOSED';
        END IF;

        IF v_reason IS NULL THEN
            SELECT st."studentId", st."studentNumber", concat_ws(' ', st."firstName", st."middleName", st."lastName", st.suffix)
            INTO v_student_id, v_student_number, v_student_name
            FROM "StudentUserLinks" sul JOIN "Users" u ON u."userId" = sul."userId" JOIN "Students" st ON st."studentId" = sul."studentId"
            WHERE sul."userId" = p_authenticated_user_id AND u."isActive" = TRUE AND st."isActive" = TRUE;
            IF NOT FOUND THEN v_reason := 'STUDENT_ACCOUNT_NOT_LINKED'; END IF;
        END IF;

        IF v_reason IS NULL THEN
            SELECT ep."eventParticipantId" INTO v_participant_id FROM "EventParticipants" ep WHERE ep."eventSessionId" = v_session_id AND ep."studentId" = v_student_id FOR UPDATE;
            IF NOT FOUND THEN v_reason := 'NOT_ON_SESSION_ROSTER'; END IF;
        END IF;

        IF v_reason IS NULL THEN
            SELECT ar."attendanceRecordId", ar."checkedInAtUtc", ar."checkedOutAtUtc", ar."isExcused", ar."excuseReason"
            INTO v_attendance_record_id, v_checked_in, v_checked_out, v_is_excused, v_excuse_reason
            FROM "AttendanceRecords" ar WHERE ar."eventParticipantId" = v_participant_id;

            IF v_qr_action = 'AUTO' THEN
                IF v_checked_in IS NULL THEN v_action := 'IN';
                ELSIF v_requires_out AND v_checked_out IS NULL AND v_out_open IS NOT NULL AND v_now >= v_out_open THEN v_action := 'OUT';
                ELSE v_action := 'IN'; END IF;
            ELSE v_action := v_qr_action::VARCHAR(3); END IF;

            IF v_action = 'IN' THEN
                IF v_checked_in IS NOT NULL THEN v_result := 'NO_CHANGE'; v_reason := 'ALREADY_CHECKED_IN'; v_effective_at := v_checked_in;
                ELSIF v_now < v_in_open OR v_now > v_in_close THEN v_reason := 'OUTSIDE_CHECKIN_WINDOW';
                ELSE
                    IF v_attendance_record_id IS NULL THEN
                        INSERT INTO "AttendanceRecords" ("eventParticipantId", "checkedInAtUtc", "lastChangedByUserId", "lastChangedAtUtc")
                        VALUES (v_participant_id, v_now, p_authenticated_user_id, v_now) RETURNING "attendanceRecordId" INTO v_attendance_record_id;
                        v_is_excused := FALSE;
                    ELSE
                        UPDATE "AttendanceRecords" SET "checkedInAtUtc" = v_now, "lastChangedByUserId" = p_authenticated_user_id, "lastChangedAtUtc" = v_now WHERE "attendanceRecordId" = v_attendance_record_id;
                    END IF;
                    INSERT INTO "AttendanceLogs" ("attendanceRecordId", "actionCode", "oldCheckInAtUtc", "oldCheckOutAtUtc", "newCheckInAtUtc", "newCheckOutAtUtc", "oldIsExcused", "newIsExcused", "actorUserId")
                    VALUES (v_attendance_record_id, 'CHECK_IN', v_checked_in, v_checked_out, v_now, v_checked_out, v_is_excused, v_is_excused, p_authenticated_user_id);
                    v_checked_in := v_now; v_result := 'ACCEPTED'; v_effective_at := v_now;
                END IF;
            ELSIF v_action = 'OUT' THEN
                IF v_checked_in IS NULL THEN v_reason := 'CHECKIN_REQUIRED_FIRST';
                ELSIF v_checked_out IS NOT NULL THEN v_result := 'NO_CHANGE'; v_reason := 'ALREADY_CHECKED_OUT'; v_effective_at := v_checked_out;
                ELSIF v_requires_out = FALSE THEN v_reason := 'CHECKOUT_NOT_REQUIRED';
                ELSIF v_now < v_out_open OR v_now > v_out_close THEN v_reason := 'OUTSIDE_CHECKOUT_WINDOW';
                ELSE
                    UPDATE "AttendanceRecords" SET "checkedOutAtUtc" = v_now, "lastChangedByUserId" = p_authenticated_user_id, "lastChangedAtUtc" = v_now WHERE "attendanceRecordId" = v_attendance_record_id;
                    INSERT INTO "AttendanceLogs" ("attendanceRecordId", "actionCode", "oldCheckInAtUtc", "oldCheckOutAtUtc", "newCheckInAtUtc", "newCheckOutAtUtc", "oldIsExcused", "newIsExcused", "actorUserId")
                    VALUES (v_attendance_record_id, 'CHECK_OUT', v_checked_in, v_checked_out, v_checked_in, v_now, v_is_excused, v_is_excused, p_authenticated_user_id);
                    v_checked_out := v_now; v_result := 'ACCEPTED'; v_effective_at := v_now;
                END IF;
            END IF;
        END IF;

        IF v_participant_id IS NOT NULL AND v_checked_in IS NOT NULL THEN
            SELECT va."attendanceStatus"::VARCHAR(30) INTO v_attendance_status FROM "VwEventAttendance" va WHERE va."eventParticipantId" = v_participant_id;
        END IF;

        INSERT INTO "AttendanceScanAttempts" (
            "eventSessionId", "eventRegistrationId", "eventParticipantId", "attendanceDeviceId", "tokenHash", "actionCode",
            "scanResultCode", "failureReasonCode", "processedByUserId", "scannedAtUtc", "eventSessionQrTokenId", "resolvedStudentId",
            "scanMethodCode", "clientRequestId", "clientFingerprintHash", "ipAddress", "attendanceStatusCode", "attendanceEffectiveAtUtc"
        ) VALUES (
            v_session_id, NULL, v_participant_id, NULL, p_token_hash, v_action,
            v_result, v_reason, p_authenticated_user_id, v_now, v_qr_id, v_student_id,
            'STUDENT_SCANNED_EVENT_QR', p_client_request_id, p_client_fingerprint_hash, p_ip_address,
            v_attendance_status, v_effective_at
        );

        RETURN QUERY SELECT v_result, v_reason, v_event_id, v_event_name, v_session_id, v_session_name,
            v_student_id, v_student_number, v_student_name, v_action, v_attendance_status, COALESCE(v_effective_at, v_now);
    END $function$;
  `);
}

async function ignoreDuplicate(db: Queryable, sql: string): Promise<void> {
  try {
    await db.query(sql);
  } catch (e: unknown) {
    const code = e && typeof e === 'object' && 'code' in e ? String((e as { code: unknown }).code) : '';
    // 42710/42P07: constraint/index already exists
    // 42703: hardened tables omit app-only key columns (e.g. EventSessions.academicTermId)
    if (code === '42710' || code === '42P07' || code === '42703') return;
    throw e;
  }
}


/** Rename snake_case tables/columns to quoted PascalCase / camelCase. */
export async function renameSnakeToPascal(db: Queryable): Promise<void> {
  if (await relationExists(db, q('Users'))) return;
  if (!(await relationExists(db, 'users'))) return;

  await db.query('DROP VIEW IF EXISTS v_attendance_session_status');
  await db.query(`DROP VIEW IF EXISTS ${q('AttendanceSessionStatus')}`);

  for (const [from, to] of SNAKE_TABLES_TO_PASCAL) {
    if (await relationExists(db, from)) {
      await db.query(`ALTER TABLE ${from} RENAME TO ${q(to)}`);
    }
  }

  for (const [, table] of SNAKE_TABLES_TO_PASCAL) {
    if (!(await relationExists(db, q(table)))) continue;
    for (const [from, to] of SNAKE_COLUMNS_TO_CAMEL) {
      if (await columnExists(db, table, from)) {
        await db.query(`ALTER TABLE ${q(table)} RENAME COLUMN ${from} TO ${q(to)}`);
      }
    }
  }
}

/** Strip the previous multi-tenant columns/tables from an already-installed schema. */
export async function dropTenantsIfPresent(db: Queryable): Promise<void> {
  const hasTenants = await relationExists(db, 'tenants');
  const hasTenantCol = await columnExists(db, 'students', 'tenant_id');
  if (!hasTenants && !hasTenantCol) return;

  await db.query('DROP VIEW IF EXISTS v_attendance_session_status');

  if (await relationExists(db, 'user_tenants')) {
    await db.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS role varchar(20)');
    await db.query(
      `UPDATE users u
       SET role = ut.role_code
       FROM user_tenants ut
       WHERE ut.user_id = u.user_id AND (u.role IS NULL OR u.role = '')`,
    );
  }
  if (await columnExists(db, 'users', 'role')) {
    await db.query(`UPDATE users SET role = 'moderator' WHERE role IS NULL`);
    await db.query('ALTER TABLE users ALTER COLUMN role SET NOT NULL');
  }

  const tables = [
    'attendance_logs',
    'attendance_corrections',
    'attendance_records',
    'event_participants',
    'event_sessions',
    'events',
    'student_enrollments',
    'students',
    'sections',
    'academic_programs',
    'academic_terms',
    'academic_years',
  ];
  for (const table of tables) {
    if ((await relationExists(db, table)) && (await columnExists(db, table, 'tenant_id'))) {
      await db.query(`ALTER TABLE ${table} DROP COLUMN tenant_id CASCADE`);
    }
  }

  await db.query('DROP TABLE IF EXISTS user_tenants CASCADE');
  await db.query('DROP TABLE IF EXISTS tenants CASCADE');
}


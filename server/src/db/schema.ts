export async function importLegacyData(db: Queryable): Promise<void> {
  if (!(await relationExists(db, '_legacy_users'))) return;

  await db.query(
    `INSERT INTO ${q('Users')} (${q('userId')}, username, ${q('passwordHash')}, ${q('displayName')}, role, ${q('createdAtUtc')}, ${q('updatedAtUtc')})
     OVERRIDING SYSTEM VALUE
     SELECT id, username, password_hash, name,
            CASE WHEN role IN ('superadmin', 'moderator', 'student') THEN role ELSE 'moderator' END,
            created_at, updated_at
     FROM _legacy_users`,
  );
  await db.query(
    `SELECT setval(pg_get_serial_sequence('${q('Users')}', 'userId'), COALESCE((SELECT MAX(${q('userId')}) FROM ${q('Users')}), 1), true)`,
  );

  await db.query(
    `INSERT INTO ${q('Students')} (
        ${q('studentId')}, ${q('studentNumber')}, ${q('firstName')}, ${q('lastName')}, ${q('middleName')},
        ${q('photoUrl')}, ${q('createdAtUtc')}, ${q('updatedAtUtc')}
     )
     OVERRIDING SYSTEM VALUE
     SELECT
       s.id,
       s.student_id_code,
       COALESCE(NULLIF(split_part(btrim(s.full_name), ' ', 1), ''), s.full_name),
       CASE
         WHEN position(' ' IN btrim(s.full_name)) = 0 THEN btrim(s.full_name)
         ELSE regexp_replace(btrim(s.full_name), '^\\S+\\s+', '')
       END,
       NULL,
       s.photo_url,
       s.created_at,
       s.updated_at
     FROM _legacy_students s`,
  );
  await db.query(
    `SELECT setval(pg_get_serial_sequence('${q('Students')}', 'studentId'), COALESCE((SELECT MAX(${q('studentId')}) FROM ${q('Students')}), 1), true)`,
  );

  await db.query(
    `INSERT INTO ${q('StudentEnrollments')} (
        ${q('studentId')}, ${q('academicTermId')}, ${q('academicProgramId')}, ${q('sectionId')},
        ${q('yearLevel')}, ${q('enrollmentStatusCode')}, ${q('effectiveFromUtc')}
     )
     SELECT s.${q('studentId')}, term.${q('academicTermId')}, p.${q('academicProgramId')}, NULL,
            1, 'ENROLLED', clock_timestamp()
     FROM ${q('Students')} s
     JOIN ${q('AcademicTerms')} term ON term.${q('termCode')} = 'DEFAULT'
     JOIN ${q('AcademicPrograms')} p ON p.${q('programCode')} = 'BSIT'`,
  );

  await db.query(
    `INSERT INTO ${q('Events')} (
        ${q('eventId')}, ${q('academicTermId')}, ${q('eventCode')}, ${q('eventName')}, ${q('eventStartDate')}, ${q('eventEndDate')},
        ${q('eventStatusCode')}, ${q('createdByUserId')}, ${q('createdAtUtc')}, ${q('updatedAtUtc')}
     )
     OVERRIDING SYSTEM VALUE
     SELECT
       e.id,
       term.${q('academicTermId')},
       'EVT-' || e.id::text,
       e.name,
       e.event_date::date,
       e.event_date::date,
       CASE WHEN e.is_active THEN 'PUBLISHED' ELSE 'CLOSED' END,
       e.created_by,
       e.created_at,
       e.updated_at
     FROM _legacy_events e
     JOIN ${q('AcademicTerms')} term ON term.${q('termCode')} = 'DEFAULT'`,
  );
  await db.query(
    `SELECT setval(pg_get_serial_sequence('${q('Events')}', 'eventId'), COALESCE((SELECT MAX(${q('eventId')}) FROM ${q('Events')}), 1), true)`,
  );

  await db.query(
    `INSERT INTO ${q('EventSessions')} (
        ${q('eventSessionId')}, ${q('eventId')}, ${q('academicTermId')}, ${q('sessionCode')}, ${q('sessionName')},
        ${q('startsAtUtc')}, ${q('endsAtUtc')}, ${q('checkInOpensAtUtc')}, ${q('checkInClosesAtUtc')}, ${q('lateAfterUtc')},
        ${q('checkOutOpensAtUtc')}, ${q('checkOutClosesAtUtc')}, ${q('sortOrder')}
     )
     OVERRIDING SYSTEM VALUE
     SELECT
       w.id,
       w.event_id,
       ev.${q('academicTermId')},
       'S' || w.id::text,
       w.session_label,
       (ev.${q('eventStartDate')}::timestamp + w.start_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.end_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.start_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.end_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.start_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.start_time::time),
       (ev.${q('eventStartDate')}::timestamp + w.end_time::time),
       w.sort_order
     FROM _legacy_session_windows w
     JOIN ${q('Events')} ev ON ev.${q('eventId')} = w.event_id`,
  );
  await db.query(
    `SELECT setval(pg_get_serial_sequence('${q('EventSessions')}', 'eventSessionId'), COALESCE((SELECT MAX(${q('eventSessionId')}) FROM ${q('EventSessions')}), 1), true)`,
  );

  if (await relationExists(db, '_legacy_attendance_logs')) {
    await db.query(
      `INSERT INTO ${q('EventParticipants')} (
          ${q('eventSessionId')}, ${q('academicTermId')}, ${q('studentEnrollmentId')},
          ${q('studentId')}, ${q('addedByUserId')}
       )
       SELECT DISTINCT ON (l.session_window_id, l.student_id)
         l.session_window_id, se.${q('academicTermId')}, se.${q('studentEnrollmentId')},
         l.student_id, l.scanned_by
       FROM _legacy_attendance_logs l
       JOIN ${q('StudentEnrollments')} se
         ON se.${q('studentId')} = l.student_id AND se.${q('effectiveToUtc')} IS NULL`,
    );
    await db.query(
      `INSERT INTO ${q('AttendanceRecords')} (${q('eventParticipantId')}, ${q('lastChangedByUserId')})
       SELECT ep.${q('eventParticipantId')}, ep.${q('addedByUserId')}
       FROM ${q('EventParticipants')} ep
       ON CONFLICT (${q('eventParticipantId')}) DO NOTHING`,
    );
    await db.query(
      `INSERT INTO ${q('AttendanceLogs')} (
          ${q('attendanceRecordId')}, ${q('actionCode')},
          ${q('newCheckInAtUtc')}, ${q('newCheckOutAtUtc')}, ${q('newIsExcused')},
          ${q('actorUserId')}, ${q('recordedAtUtc')}, ${q('deviceNote')}, ${q('isCancelled')}
       )
       SELECT
         ar.${q('attendanceRecordId')},
         CASE WHEN l.direction = 'OUT' THEN 'CHECK_OUT' ELSE 'CHECK_IN' END,
         CASE WHEN l.direction = 'OUT' THEN NULL ELSE l.scanned_at END,
         CASE WHEN l.direction = 'OUT' THEN l.scanned_at ELSE NULL END,
         false,
         l.scanned_by,
         l.scanned_at,
         l.device_note,
         COALESCE(l.status = 'cancelled', false)
       FROM _legacy_attendance_logs l
       JOIN ${q('EventParticipants')} ep
         ON ep.${q('eventSessionId')} = l.session_window_id AND ep.${q('studentId')} = l.student_id
       JOIN ${q('AttendanceRecords')} ar
         ON ar.${q('eventParticipantId')} = ep.${q('eventParticipantId')}`,
    );
    await db.query(
      `UPDATE ${q('AttendanceRecords')} ar
       SET ${q('checkedInAtUtc')} = sub.cin,
           ${q('checkedOutAtUtc')} = CASE WHEN sub.cin IS NULL THEN NULL ELSE sub.cout END,
           ${q('lastChangedAtUtc')} = clock_timestamp()
       FROM (
         SELECT
           ${q('attendanceRecordId')},
           MIN(${q('recordedAtUtc')}) FILTER (WHERE ${q('actionCode')} = 'CHECK_IN' AND NOT ${q('isCancelled')}) AS cin,
           MIN(${q('recordedAtUtc')}) FILTER (WHERE ${q('actionCode')} = 'CHECK_OUT' AND NOT ${q('isCancelled')}) AS cout
         FROM ${q('AttendanceLogs')}
         GROUP BY ${q('attendanceRecordId')}
       ) sub
       WHERE ar.${q('attendanceRecordId')} = sub.${q('attendanceRecordId')}`,
    );
  }

  await db.query(`DROP TABLE IF EXISTS _legacy_attendance_logs CASCADE`);
  await db.query(`DROP TABLE IF EXISTS _legacy_session_windows CASCADE`);
  await db.query(`DROP TABLE IF EXISTS _legacy_events CASCADE`);
  await db.query(`DROP TABLE IF EXISTS _legacy_students CASCADE`);
  await db.query(`DROP TABLE IF EXISTS _legacy_users CASCADE`);
}
